        <h2 class="section-title">Frequently Asked Questions</h2>
        <p style="color: var(--text-gray); margin-bottom: 2rem;">Find answers to common questions about eBayan services and features.</p>

        <div class="faq-item" onclick="toggleFaq(this)">
            <div class="faq-question">
                <span>What is eBayan?</span>
                <span class="faq-icon">+</span>
            </div>
            <div class="faq-answer">
                eBayan is a comprehensive government portal that provides Filipino citizens with easy access to government services, announcements, and information. It allows you to file complaints, request documents, and stay updated with local government activities from the comfort of your home.
            </div>
        </div>

        <div class="faq-item" onclick="toggleFaq(this)">
            <div class="faq-question">
                <span>How do I create an account?</span>
                <span class="faq-icon">+</span>
            </div>
            <div class="faq-answer">
                Click on the "Sign Up" button on the login page, fill in your personal information including name, birthday, contact details, and address. You can also sign up using your Google account for faster registration. After signing up, you'll need to verify your account to access all features.
            </div>
        </div>

        <div class="faq-item" onclick="toggleFaq(this)">
            <div class="faq-question">
                <span>Why do I need to verify my account?</span>
                <span class="faq-icon">+</span>
            </div>
            <div class="faq-answer">
                Account verification ensures the security of your personal information and confirms that you are a legitimate user. Verified accounts have access to all eBayan features including document requests, complaint filing, and admin subscription options.
            </div>
        </div>

        <div class="faq-item" onclick="toggleFaq(this)">
            <div class="faq-question">
                <span>What services are available on eBayan?</span>
                <span class="faq-icon">+</span>
            </div>
            <div class="faq-answer">
                eBayan offers a wide range of services including document requests (birth certificates, barangay clearance), business permits, building permits, tax services, complaint filing, and access to local government announcements. You can also view information about your city and barangay officials.
            </div>
        </div>

        <div class="faq-item" onclick="toggleFaq(this)">
            <div class="faq-question">
                <span>How do I file a complaint?</span>
                <span class="faq-icon">+</span>
            </div>
            <div class="faq-answer">
                Navigate to the "Complaints" section from the main menu. Fill out the complaint form with your details and a description of your concern. You can file complaints at the national, city, or barangay level depending on the nature of your issue.
            </div>
        </div>

        <div class="faq-item" onclick="toggleFaq(this)">
            <div class="faq-question">
                <span>What is the Admin Subscription?</span>
                <span class="faq-icon">+</span>
            </div>
            <div class="faq-answer">
                The Admin Subscription is designed for barangay officials and administrators who want to manage their barangay's information and services on eBayan. It provides tools for posting announcements, managing services, and responding to citizen complaints. Subscribers need to provide official barangay documentation for verification.
            </div>
        </div>

        <div class="faq-item" onclick="toggleFaq(this)">
            <div class="faq-question">
                <span>How can I update my profile information?</span>
                <span class="faq-icon">+</span>
            </div>
            <div class="faq-answer">
                Click on your profile avatar in the top right corner and select "User Profile". You can update your name, contact number, address, and other personal information. Note that your email address cannot be changed after registration for security purposes.
            </div>
        </div>

        <div class="faq-item" onclick="toggleFaq(this)">
            <div class="faq-question">
                <span>How do I change my password?</span>
                <span class="faq-icon">+</span>
            </div>
            <div class="faq-answer">
                Go to Settings from the profile dropdown menu, then select "Change Password". You'll need to enter your current password and your new password twice to confirm the change. Make sure to use a strong password with at least 8 characters.
            </div>
        </div>

        <div class="faq-item" onclick="toggleFaq(this)">
            <div class="faq-question">
                <span>Is my personal information secure?</span>
                <span class="faq-icon">+</span>
            </div>
            <div class="faq-answer">
                Yes, eBayan takes data security seriously. All personal information is encrypted and stored securely. We follow strict data protection protocols and comply with the Data Privacy Act of 2012. Your information is only used for providing government services and is never shared with third parties without your consent.
            </div>
        </div>

